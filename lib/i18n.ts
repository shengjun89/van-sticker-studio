export const STRINGS: Record<Lang, Record<StringKey, string>> = { en, zh };

/** Generation-slot lifecycle. Logic compares these enums, never display text. */
export type SlotStatus = 'waiting' | 'drawing' | 'failed' | 'done';
export const SLOT_STATUSES: readonly SlotStatus[] = [
  'waiting',
  'drawing',
  'failed',
  'done',
];

export function t(
  lang: Lang,
  key: StringKey,
  params?: Record<string, string | number>,
): string {
  let text = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (params)
    for (const [name, value] of Object.entries(params))
      text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
